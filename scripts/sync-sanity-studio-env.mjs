import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

function parseEnvFile(filePath) {
  const vars = {};

  if (!existsSync(filePath)) {
    return vars;
  }

  for (const line of readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();

    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separatorIndex = trimmed.indexOf("=");

    if (separatorIndex === -1) {
      continue;
    }

    const key = trimmed.slice(0, separatorIndex).trim();
    let value = trimmed.slice(separatorIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    vars[key] = value;
  }

  return vars;
}

const root = process.cwd();
const envLocalPath = resolve(root, ".env.local");
const vars = parseEnvFile(envLocalPath);

const projectId =
  vars.SANITY_STUDIO_PROJECT_ID || vars.NEXT_PUBLIC_SANITY_PROJECT_ID || "";
const dataset =
  vars.SANITY_STUDIO_DATASET || vars.NEXT_PUBLIC_SANITY_DATASET || "production";
const apiVersion =
  vars.SANITY_STUDIO_API_VERSION ||
  vars.NEXT_PUBLIC_SANITY_API_VERSION ||
  "2024-01-01";

const generatedPath = resolve(root, "sanity/studio-env.generated.ts");
const generatedSource = `// Generated by scripts/sync-sanity-studio-env.mjs — do not edit
export const projectId = ${JSON.stringify(projectId)};
export const dataset = ${JSON.stringify(dataset)};
export const apiVersion = ${JSON.stringify(apiVersion)};
`;

writeFileSync(generatedPath, generatedSource);

if (!projectId) {
  process.exit(0);
}

const studioEnv = [
  "# Generated by scripts/sync-sanity-studio-env.mjs",
  "# Sanity Studio reads SANITY_STUDIO_* variables in the browser bundle.",
  `SANITY_STUDIO_PROJECT_ID=${projectId}`,
  `SANITY_STUDIO_DATASET=${dataset}`,
  `SANITY_STUDIO_API_VERSION=${apiVersion}`,
  "",
].join("\n");

for (const mode of ["development", "production"]) {
  writeFileSync(resolve(root, `.env.${mode}.local`), studioEnv);
}
